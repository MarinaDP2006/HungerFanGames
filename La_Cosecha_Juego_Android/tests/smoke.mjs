import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {districts,characters,canonEditions,arenaTypes,mentors} from '../js/data.js';
let screen={innerHTML:''},indicator={textContent:''};
const document={querySelector:(s)=>s==='#screen'?screen:s==='#save-indicator'?indicator:null};
const context={districts,characters,canonEditions,arenaTypes,mentors,document,console,Math,Date,JSON,Number,String,Array,Object,Map,Set,Blob:class{},URL:{},localStorage:{setItem(){},getItem(){return null}},alert(){},navigator:{},window:{},
  setTimeout,clearTimeout};
let src=fs.readFileSync(new URL('../js/app.js',import.meta.url),'utf8');
src=src.replace(/^import .*\n/,'');
src=src.slice(0,src.indexOf("document.addEventListener('click'"));
src += `\nrenderGame=()=>{};president=()=>{};globalThis.testApi={setGame(v){game=v},getGame(){return game},triggerCampaignEvent,resolveStoryChoice,initWarCampaign,warAction,warRound,updateRebellionArc};`;
vm.runInNewContext(src,context,{filename:'app.js'});
const api=context.testApi;
const districtsState=districts.slice(0,13).map(d=>({id:d.id,name:d.name,stability:55,production:60,food:55,peacekeepers:35,population:1000000,morale:50,hidden:false}));
api.setGame({mode:'president',day:1,resources:70,rebellion:82,rebellionArc:'civil-war',order:50,approval:50,economy:50,events:[],districts:districtsState,selectedDistrict:12,warCasualties:0,president:{name:'Test',bio:'',personality:'just'}});
api.initWarCampaign();
let g=api.getGame();
assert.equal(g.war.fronts.length,4,'war fronts initialized');
assert.ok(g.war.fronts.some(f=>f.district===g.selectedDistrict),'selected district points at an active front');
const beforePopulation=g.districts.find(d=>d.id===g.selectedDistrict).population;
const beforeResources=g.resources;
api.warAction('evacuate');g=api.getGame();
assert.ok(g.districts.find(d=>d.id===g.selectedDistrict).population<beforePopulation,'evacuation moves civilians');
assert.ok(g.resources<beforeResources,'war actions spend resources');
assert.ok(g.war.civilianRisk<35,'evacuation reduces civilian risk');
const beforeRound=g.war.round;api.warAction('negotiate');g=api.getGame();
assert.ok(g.war.round>beforeRound,'actions advance the war round');
assert.ok(g.war.ceasefire>0,'negotiation advances ceasefire');
// Branching story events and relationship persistence
api.setGame({mode:'story',edition:50,arenaTurn:3,flags:{},relationships:{maysilee:0},log:[],support:10,rebellion:0,skill:5,inventory:[],tributes:[],playerSector:1,stealth:0});
api.triggerCampaignEvent();g=api.getGame();assert.equal(g.pendingStoryEvent.thread,'maysilee');
api.resolveStoryChoice('share');g=api.getGame();assert.equal(g.relationships.maysilee,3);assert.ok(g.inventory.includes('refugio compartido'));
api.setGame({mode:'story',edition:74,arenaTurn:6,flags:{},relationships:{},log:[],support:10,rebellion:0,health:80,stealth:0});
api.triggerCampaignEvent();g=api.getGame();assert.equal(g.pendingStoryEvent.thread,'memory');
api.resolveStoryChoice('defy');g=api.getGame();assert.ok(g.flags.openDefiance);assert.ok(g.rebellion>0);
api.setGame({mode:'story',edition:75,arenaTurn:6,flags:{},relationships:{},log:[],support:10,rebellion:0,fatigue:0,inventory:[]});
api.triggerCampaignEvent();g=api.getGame();assert.equal(g.pendingStoryEvent.thread,'clock');
api.resolveStoryChoice('prepare');g=api.getGame();assert.ok(g.flags.clockPlan);assert.ok(g.inventory.includes('cable conductor'));
